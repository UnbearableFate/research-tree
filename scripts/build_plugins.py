#!/usr/bin/env python3
"""Assemble independently installable marketplaces from shared code and host adapters.

Only the Python standard library is needed. Source directories never contain generated
copies. Each output directory is a complete marketplace; each ZIP contains that directory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ADAPTERS = {"claude": "claude-mod/research-tree", "codex": "codex-plugin/research-tree"}
MANIFESTS = {"claude": ".claude-plugin/plugin.json", "codex": ".codex-plugin/plugin.json"}
IGNORED = {"__pycache__", ".venv", "node_modules", ".DS_Store"}


def source_files(root: Path):
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if any(p in IGNORED for p in rel.parts) or path.suffix in {".pyc", ".pyo"}:
            continue
        if rel.parts[:2] == (".claude-plugin", "types"):
            continue  # Generated by the local Claude installation, not plugin source.
        if path.is_symlink():
            raise ValueError(f"source symlinks are not supported: {path}")
        if path.is_file():
            yield rel, path


def assemble(target: str, destination: Path, repo: Path = REPO) -> dict:
    """Build into an empty directory; reject accidental adapter copies of shared files."""
    adapter = repo / ADAPTERS[target]
    manifest_path = adapter / MANIFESTS[target]
    if not manifest_path.is_file():
        raise ValueError(f"{target} adapter is incomplete: missing {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("name") != "research-tree" or not manifest.get("version"):
        raise ValueError(f"invalid plugin identity: {manifest_path}")
    for required in ("tools/copy_config.sh", "tools/research_db.py", "tools/research_tree.py", "tools/project_config.py",
                     "tools/send_message.py", "tools/build_site.py", "schema/research_tree.sql",
                     "schema/create_db.py", "schema/config.schema.json", "schema/config.template.yaml", "schema/cleanup.template.py",
                     "schema/message.schema.json", "rules/research-tree-rules.md"):
        if not (repo / "shared/research-tree" / required).is_file():
            raise ValueError(f"shared core is incomplete: missing {required}")
    plugin = destination / "plugins" / "research-tree"
    files = {}
    for source in (repo / "shared/research-tree", adapter):
        for rel, path in source_files(source):
            if str(rel) in files:
                raise ValueError(f"shared/adapter path collision: {target}/{rel}; keep one source")
            if str(rel) in {"pyproject.toml", "uv.lock"}:
                raise ValueError(f"dependency source collision: {target}/{rel}; use repository root")
            output = plugin / rel
            output.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, output)
            output.chmod(0o755 if path.stat().st_mode & 0o111 else 0o644)
            files[str(rel)] = hashlib.sha256(output.read_bytes()).hexdigest()
    catalog_path = (".claude-plugin/marketplace.json" if target == "claude"
                    else ".agents/plugins/marketplace.json")
    catalog = json.loads((repo / catalog_path).read_text(encoding="utf-8"))
    entry = next(p for p in catalog["plugins"] if p["name"] == "research-tree")
    entry["source"] = ("./plugins/research-tree" if target == "claude" else
                       {"source": "local", "path": "./plugins/research-tree"})
    catalog["plugins"] = [entry]
    output = destination / catalog_path
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # Keep dependency requirements with the artifact; do not ship the developer environment.
    shutil.copyfile(repo / "pyproject.toml", plugin / "pyproject.toml")
    shutil.copyfile(repo / "uv.lock", plugin / "uv.lock")
    for name in ("pyproject.toml", "uv.lock"):
        files[name] = hashlib.sha256((plugin / name).read_bytes()).hexdigest()
    record = {"target": target, "name": manifest["name"], "version": manifest["version"],
              "files": dict(sorted(files.items()))}
    (destination / "BUILD.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return record


def archive(source: Path, output: Path, prefix: str) -> None:
    """Stable ordering, timestamps and permissions make equal inputs produce equal ZIPs."""
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for rel, path in source_files(source):
            info = zipfile.ZipInfo(f"{prefix}/{rel}", date_time=(2020, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = (0o100000 | (path.stat().st_mode & 0o777)) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            bundle.writestr(info, path.read_bytes())


def build(targets: list[str], output: Path, repo: Path = REPO) -> list[dict]:
    output = output.resolve()
    repo = repo.resolve()
    # Replacement is allowed only for a previously generated artifact, never a source tree.
    source_roots = [repo / "shared", repo / "claude-mod", repo / "codex-plugin", repo / "scripts", repo / "tests"]
    if any(output == p or p in output.parents or output in p.parents for p in source_roots):
        raise ValueError(f"output overlaps source directories: {output}")
    output.mkdir(parents=True, exist_ok=True)
    for target in targets:
        old = output / target
        if old.is_symlink() or (old.exists() and not (old / "BUILD.json").is_file()):
            raise ValueError(f"refusing to replace non-build directory: {old}")
    results = []
    with tempfile.TemporaryDirectory(prefix=".research-build-", dir=output) as work:
        staging = Path(work)
        # Validate and assemble all targets before replacing any existing output.
        for target in targets:
            record = assemble(target, staging / target, repo)
            filename = f"research-tree-{target}-{record['version']}.zip"
            archive(staging / target, staging / filename, f"research-tree-{target}")
            results.append({**record, "archive": str(output / filename)})
        for record in results:
            target = record["target"]
            old = output / target
            if old.exists():
                shutil.rmtree(old)
            (staging / target).replace(old)
            filename = Path(record["archive"]).name
            (staging / filename).replace(output / filename)
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", choices=[*ADAPTERS, "all"], default="all")
    parser.add_argument("--output", type=Path, default=REPO / "dist")
    args = parser.parse_args()
    try:
        results = build(list(ADAPTERS) if args.target == "all" else [args.target], args.output)
    except (ValueError, OSError, KeyError) as exc:
        parser.exit(2, f"build failed: {exc}\n")
    for record in results:
        print(f"{record['target']}: {len(record['files'])} files; {record['archive']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
